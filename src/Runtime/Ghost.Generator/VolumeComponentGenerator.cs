using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace Ghost.Generator;

[Generator]
public class VolumeComponentGenerator : IIncrementalGenerator
{
    private const string VOLUME_COMPONENT_ATTRIBUTE = "Ghost.Core.VolumeComponentAttribute";
    private const string HARDCUT_ATTRIBUTE = "Ghost.Core.HardcutAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                VOLUME_COMPONENT_ATTRIBUTE,
                (node, _) => node is StructDeclarationSyntax,
                (ctx, _) => ctx.TargetSymbol as INamedTypeSymbol)
            .Where(symbol => symbol != null)
            .Collect();

        context.RegisterSourceOutput(candidates, GenerateVolumeComponentCode);
    }

    private static void GenerateVolumeComponentCode(SourceProductionContext context, ImmutableArray<INamedTypeSymbol?> symbols)
    {
        if (symbols.IsDefaultOrEmpty)
        {
            return;
        }

        var regSb = new StringBuilder();
        var hasRegistered = false;

        foreach (var item in symbols.Distinct(SymbolEqualityComparer.Default))
        {
            if (item is not INamedTypeSymbol symbol)
            {
                continue;
            }

            var code = GenerateForSymbol(symbol);
            if (!string.IsNullOrEmpty(code))
            {
                context.AddSource($"{symbol.Name}.VolumeComponent.g.cs", code);
                var fullTypeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                regSb.AppendLine($"        global::Ghost.Engine.Volumes.VolumeRegistry.Register<{fullTypeName}>(&{fullTypeName}.ApplySerializedField, &{fullTypeName}.GetOrAddDefaultInMap);");
                hasRegistered = true;
            }
        }

        if (hasRegistered)
        {
            var regCode = $@"// <auto-generated/>
#nullable enable

[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
internal static partial class g_volume_registration
{{
    [global::System.Runtime.CompilerServices.ModuleInitializer]
    internal static unsafe void RegisterVolumeComponentSerializers()
    {{
{regSb}
    }}
}}";
            context.AddSource("g_volume_registration.gen.cs", regCode);
        }
    }

    private static string GenerateForSymbol(INamedTypeSymbol symbol)
    {
        var ns = symbol.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingNamespace.ToDisplayString();
        var fullTypeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var typeName = symbol.Name;

        var directSb = new StringBuilder();
        var blendSb = new StringBuilder();

        var fields = symbol.GetMembers()
            .OfType<IFieldSymbol>()
            .Where(f => !f.IsStatic && !f.IsConst);

        foreach (var field in fields)
        {
            var fieldName = field.Name;
            var fieldType = field.Type;
            var isNullable = false;
            var targetType = fieldType;

            if (fieldType is INamedTypeSymbol namedType && namedType.ConstructedFrom.SpecialType == SpecialType.System_Nullable_T)
            {
                isNullable = true;
                targetType = namedType.TypeArguments[0];
            }

            var hasHardcut = field.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == HARDCUT_ATTRIBUTE);
            var targetTypeName = targetType.ToDisplayString();

            var isSlerp = !hasHardcut && IsQuaternionType(targetTypeName);
            var isLerp = !hasHardcut && !isSlerp && IsInterpolatableType(targetTypeName, targetType);

            if (isNullable)
            {
                directSb.AppendLine(@$"
            if (source.{fieldName}.HasValue)
            {{
                target.{fieldName} = source.{fieldName}.Value;
            }}");

                if (isSlerp)
                {
                    blendSb.AppendLine(@$"
        if (source.{fieldName} is {{ }} v_{fieldName})
        {{
            target.{fieldName} = global::Misaki.HighPerformance.Mathematics.math.slerp(target.{fieldName}.GetValueOrDefault(), v_{fieldName}, weight);
        }}");
                }
                else if (isLerp)
                {
                    blendSb.AppendLine(@$"
        if (source.{fieldName} is {{ }} v_{fieldName})
        {{
            target.{fieldName} = global::Misaki.HighPerformance.Mathematics.math.lerp(target.{fieldName}.GetValueOrDefault(), v_{fieldName}, weight);
        }}");
                }
                else
                {
                    // Hardcut
                    blendSb.AppendLine(@$"
        if (source.{fieldName} is {{ }} v_{fieldName})
        {{
            target.{fieldName} = v_{fieldName};
        }}");
                }
            }
            else
            {
                directSb.AppendLine(@$"
            target.{fieldName} = source.{fieldName};");

                if (isSlerp)
                {
                    blendSb.AppendLine(@$"
        target.{fieldName} = global::Misaki.HighPerformance.Mathematics.math.slerp(target.{fieldName}, source.{fieldName}, weight);");
                }
                else if (isLerp)
                {
                    blendSb.AppendLine(@$"
        target.{fieldName} = global::Misaki.HighPerformance.Mathematics.math.lerp(target.{fieldName}, source.{fieldName}, weight);");
                }
                else
                {
                    blendSb.AppendLine(@$"
        target.{fieldName} = source.{fieldName};");
                }
            }
        }

        var hasDefault = symbol.GetMembers("Default").Any();
        var defaultPropertyCode = hasDefault
            ? string.Empty
            : $@"
    /// <summary>
    /// Gets the default value when not overridden.
    /// </summary>
    public static {fullTypeName} Default => default;
";

        var fieldBodySb = new StringBuilder();
        var hasFieldBody = FieldDeserializerGenHelper.TryEmitFieldSwitchBody(fieldBodySb, symbol, "        ", out _);
        var applyFieldBody = hasFieldBody
            ? fieldBodySb.ToString()
            : "        _ = componentPtr;\n        _ = fieldNameHash;\n        _ = reader;\n";

        var namespaceLine = string.IsNullOrEmpty(ns) ? string.Empty : $"namespace {ns};\n";

        return @$"
// <auto-generated/>
#nullable enable

{namespaceLine}
partial struct {typeName} : global::Ghost.Engine.Volumes.IVolumeComponent<{fullTypeName}>
{{
{defaultPropertyCode}
    /// <summary>
    /// Blends the source volume settings into the target using the specified weight.
    /// </summary>
    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
    public static void Blend(ref {fullTypeName} target, in {fullTypeName} source, float weight)
    {{
        if (weight <= 0.0f)
        {{
            return;
        }}

        if (weight >= 1.0f)
        {{
{directSb}
            return;
        }}

{blendSb}
    }}

    internal static unsafe void* GetOrAddDefaultInMap(ref global::Ghost.Engine.Volumes.UnmanagedTypeMap storage)
    {{
        var typeId = global::Ghost.Engine.Volumes.VolumeBlenderTrampoline<{fullTypeName}>.TypeId;
        if (!storage.TryGetPtr(typeId, out var ptr))
        {{
            var defaultVal = default({fullTypeName});
            storage.Set(typeId, in defaultVal);
            storage.TryGetPtr(typeId, out ptr);
        }}

        return ptr;
    }}

    internal static unsafe void ApplySerializedField(void* componentPtr, uint fieldNameHash, in global::Ghost.Core.SceneFieldReader reader)
    {{
{applyFieldBody}    }}
}}";
    }

    private static bool IsQuaternionType(string typeName)
    {
        return typeName == "Misaki.HighPerformance.Mathematics.quaternion"
            || typeName == "quaternion"
            || typeName == "System.Numerics.Quaternion"
            || typeName == "Quaternion";
    }

    private static bool IsInterpolatableType(string typeName, ITypeSymbol type)
    {
        if (type.SpecialType == SpecialType.System_Single || type.SpecialType == SpecialType.System_Double)
        {
            return true;
        }

        var simpleName = typeName.Split('.').Last();
        return simpleName switch
        {
            "float2" or "float3" or "float4" => true,
            "double2" or "double3" or "double4" => true,
            "half" or "half2" or "half3" or "half4" => true,
            "Vector2" or "Vector3" or "Vector4" => true,
            _ => false
        };
    }
}
