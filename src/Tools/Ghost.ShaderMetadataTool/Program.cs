using Ghost.Core;

namespace Ghost.ShaderMetadataTool;

public class Program
{
    public static void Main(string[] args)
    {
        Logger.Impl.OnLogAdded += static (log) => Console.WriteLine($"[{log.Level}] {log.Message}");

        if (args.Length < 2)
        {
            Console.WriteLine("Usage: Ghost.ShaderMetadataTool <input_files.txt> <asset_dir>");
            return;
        }

        var inputFileList = args[0];
        var assetDir = args[1];

        if (!File.Exists(inputFileList))
        {
            Console.WriteLine($"Input file list not found: {inputFileList}");
            return;
        }

        var files = File.ReadAllLines(inputFileList);

        var generatedFiles = new Dictionary<string, string>(StringComparer.Ordinal);

        foreach (var file in files)
        {
            if (string.IsNullOrWhiteSpace(file) || !File.Exists(file))
            {
                continue;
            }

            var text = File.ReadAllText(file);

            Utility.GenerateHLSLTypes(generatedFiles, text);
        }

        var writtenCount = 0;
        foreach (var (virtualPath, content) in generatedFiles)
        {
            var macro = System.Text.RegularExpressions.Regex.Replace(virtualPath.ToUpperInvariant(), @"[^A-Z0-9_]", "_");
            var finalContent = $"// Auto-generated by Ghost.ShaderMetadataTool. Do not modify manually.\n#ifndef {macro}\n#define {macro}\n{content}\n#endif // {macro}\n";

            var relativePath = virtualPath.TrimStart('/', '\\');
            var diskPath = Path.Combine(assetDir, relativePath);

            var dir = Path.GetDirectoryName(diskPath);
            if (!string.IsNullOrEmpty(dir))
            {
                Directory.CreateDirectory(dir);
            }

            // Only write if new or content changed, preserving timestamps for incremental build
            if (!File.Exists(diskPath) || File.ReadAllText(diskPath) != finalContent)
            {
                File.WriteAllText(diskPath, finalContent);
                Console.WriteLine($"Generated HLSL on disk: {diskPath}");
                writtenCount++;
            }
        }

        Console.WriteLine($"Generated {generatedFiles.Count} HLSL file(s) ({writtenCount} updated).");
    }
}
