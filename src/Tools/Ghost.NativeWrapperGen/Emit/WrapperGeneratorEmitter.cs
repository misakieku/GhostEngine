using Ghost.NativeWrapperGen.Config;
using Ghost.NativeWrapperGen.Model;
using Ghost.NativeWrapperGen.Transform;

namespace Ghost.NativeWrapperGen.Emit;

/// <summary>
/// Emits partial struct files containing low-level method wrappers that route
/// DllImport functions from the Api class into the native struct types they belong to.
/// No wrapper classes, no properties, no owned/marshalled types — just methods.
/// </summary>
public sealed class WrapperGeneratorEmitter
{
    public static IEnumerable<GeneratedFile> Emit(NativeLibrary library, WrapperConfig config)
    {
        var naming = new NamingConventions(config);
        var resolver = new BindingTypeResolver(library);
        var router = new ActionRouter(config, resolver, naming);
        var planner = new ParameterPlanner(config);
        var skipFunctions = new HashSet<string>(config.SkipFunctions, StringComparer.Ordinal);

        var methodsByStruct = new Dictionary<string, List<RoutedMethod>>(StringComparer.Ordinal);
        var baseTypesByStruct = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);

        foreach (var func in library.Functions)
        {
            if (!func.IsDllImport || skipFunctions.Contains(func.Name))
            {
                continue;
            }

            router.RouteFunction(func, methodsByStruct, baseTypesByStruct);
        }

        var structNames = methodsByStruct.Keys.Union(baseTypesByStruct.Keys, StringComparer.Ordinal).Order(StringComparer.Ordinal);
        foreach (var structName in structNames)
        {
            methodsByStruct.TryGetValue(structName, out var methods);
            baseTypesByStruct.TryGetValue(structName, out var baseTypes);
            yield return EmitStructFile(structName, methods ?? [], baseTypes, config, naming, planner);
        }
    }

    private static GeneratedFile EmitStructFile(string structName, List<RoutedMethod> methods, HashSet<string>? baseTypes, WrapperConfig config, NamingConventions naming, ParameterPlanner planner)
    {
        var writer = new CodeWriter();

        writer.WriteLine("// <auto-generated>");
        writer.WriteLine("// This file is generated by Ghost.NativeWrapperGen. Do not edit manually.");
        writer.WriteLine("// </auto-generated>");
        writer.WriteLine();
        writer.WriteLine($"namespace {config.OutputNamespace};");
        writer.WriteLine();

        var baseTypeList = baseTypes is { Count: > 0 }
            ? " : " + string.Join(", ", baseTypes.Order(StringComparer.Ordinal))
            : string.Empty;
        writer.WriteLine($"public unsafe partial struct {structName}{baseTypeList}");
        writer.WriteLine("{");

        using (writer.IndentScope())
        {
            for (var i = 0; i < methods.Count; i++)
            {
                if (i > 0)
                {
                    writer.WriteLine();
                }

                EmitMethod(writer, methods[i], naming, planner);
            }
        }

        writer.WriteLine("}");

        return new GeneratedFile
        {
            FileName = $"{structName}.nativegen.cs",
            Content = writer.ToString(),
        };
    }

    private static void EmitMethod(CodeWriter writer, RoutedMethod routed, NamingConventions naming, ParameterPlanner planner)
    {
        var func = routed.Function;
        var nameOpts = routed.Apply.Opts?.Name;
        var methodName = naming.GetName(func.Name, nameOpts, routed.TargetStructName);
        var removeFirstParam = routed.IsInstance && (routed.Apply.Opts?.RemoveFirstParam ?? true);

        var paramPlan = planner.BuildParameterPlan(func, routed.IsInstance, removeFirstParam);
        var returnPlan = planner.PlanReturn(func);

        var crefParams = string.Join(", ", func.Parameters.Select(static p => FormatCrefType(p.TypeName)));
        writer.WriteLine("/// <summary>");
        writer.WriteLine($"/// From: <see cref=\"Api.{func.Name}({crefParams})\" />");
        writer.WriteLine("/// </summary>");
        writer.WriteLine("[System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");

        var staticModifier = routed.IsInstance ? string.Empty : "static ";
        var paramList = string.Join(", ", paramPlan.PublicParams.Select(static p => $"{p.PublicType} {p.PublicName}"));
        writer.WriteLine($"public {staticModifier}{returnPlan.PublicReturnType} {methodName}({paramList})");
        writer.WriteLine("{");

        using (writer.IndentScope())
        {
            EmitMethodBody(writer, func, routed, paramPlan, returnPlan);
        }

        writer.WriteLine("}");
    }

    private static void EmitMethodBody(CodeWriter writer, NativeFunction func, RoutedMethod routed, ParameterPlan plan, ReturnPlan returnPlan)
    {
        var wrappedParams = plan.PublicParams.Where(static p => p.WrapCall is not null).ToList();
        var args = new List<string>();

        if (plan.HasSelfParam)
        {
            var passAs = routed.Apply.Opts?.PassAs;
            args.Add(passAs is not null
                ? passAs.Replace("$TSelf", routed.TargetStructName, StringComparison.Ordinal)
                : $"({routed.TargetStructName}*)System.Runtime.CompilerServices.Unsafe.AsPointer(ref this)");
        }

        foreach (var p in plan.AllNativeParams)
        {
            if (p.IsConsumedByDerivesFrom)
            {
                args.Add(p.DerivedExpr!);
            }
            else if (!p.IsSelfParam)
            {
                args.Add(p.PassAs ?? p.PublicName);
            }
        }

        var hasReturn = !string.Equals(func.ReturnType, "void", StringComparison.Ordinal);
        var callPrefix = returnPlan.ConvertToExpr is not null
            ? "var __result = "
            : hasReturn ? "return " : string.Empty;

        EmitNestedWrapCall(writer, wrappedParams, 0, w =>
        {
            EmitApiCall(w, func.Name, args, callPrefix);
            if (returnPlan.ConvertToExpr is not null)
            {
                var returnExpr = returnPlan.ConvertToExpr.Replace("$result", "__result", StringComparison.Ordinal);
                w.WriteLine($"return {returnExpr};");
            }
        });
    }

    private static void EmitApiCall(CodeWriter writer, string functionName, List<string> args, string callPrefix)
    {
        if (args.Count <= 1)
        {
            writer.WriteLine($"{callPrefix}Api.{functionName}({string.Join(", ", args)});");
            return;
        }

        writer.WriteLine($"{callPrefix}Api.{functionName}(");
        using (writer.IndentScope())
        {
            for (var i = 0; i < args.Count; i++)
            {
                var trailing = i < args.Count - 1 ? "," : ");";
                writer.WriteLine($"{args[i]}{trailing}");
            }
        }
    }

    private static void EmitNestedWrapCall(CodeWriter writer, List<PublicParam> wrappedParams, int index, Action<CodeWriter> emitInner)
    {
        if (index >= wrappedParams.Count)
        {
            emitInner(writer);
            return;
        }

        var param = wrappedParams[index];
        var wrapCall = param.WrapCall!;
        const string callPlaceholder = "$CALL";
        var splitIndex = wrapCall.IndexOf(callPlaceholder, StringComparison.Ordinal);

        if (splitIndex < 0)
        {
            writer.WriteLine(ParameterPlanner.SubstituteArg(wrapCall, param.PublicName));
            EmitNestedWrapCall(writer, wrappedParams, index + 1, emitInner);
            return;
        }

        var before = ParameterPlanner.SubstituteArg(wrapCall[..splitIndex], param.PublicName).Trim();
        var after = ParameterPlanner.SubstituteArg(wrapCall[(splitIndex + callPlaceholder.Length)..], param.PublicName).Trim();

        if (before.EndsWith('{'))
        {
            writer.WriteLine(before[..^1].TrimEnd());
            writer.WriteLine("{");
            using (writer.IndentScope())
            {
                EmitNestedWrapCall(writer, wrappedParams, index + 1, emitInner);
            }

            if (after.StartsWith('}'))
            {
                writer.WriteLine("}");
                var remaining = after[1..].Trim();
                if (remaining.Length > 0)
                {
                    writer.WriteLine(remaining);
                }
            }
            else
            {
                if (after.Length > 0)
                {
                    writer.WriteLine(after);
                }

                writer.WriteLine("}");
            }
        }
        else
        {
            writer.WriteLine(before);
            using (writer.IndentScope())
            {
                EmitNestedWrapCall(writer, wrappedParams, index + 1, emitInner);
            }

            if (after.Length > 0)
            {
                writer.WriteLine(after);
            }
        }
    }

    private static string FormatCrefType(string typeName)
    {
        return typeName.Replace('<', '{').Replace('>', '}');
    }
}
